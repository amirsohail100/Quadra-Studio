// Function to render HTML for a list of projects into a container ID
function renderCategoryProjects(containerId, list) {
  const container = document.getElementById(containerId);
  if (!container) return;

  const html = list.map(item => {
    // Generate Tech Stack tags HTML
    const tagsHTML = item.tags
      .map(t => `<span class="tag">${t}</span>`)
      .join('');

    // Demo Button HTML (if link provided)
    const demoBtnHTML = item.demoUrl && item.demoUrl !== '#' 
      ? `<a href="${item.demoUrl}" target="_blank" rel="noopener noreferrer" class="btn-overlay live-btn"><i class="fas fa-external-link-alt"></i> Live Demo</a>` 
      : `<a href="#" target="_blank" rel="noopener noreferrer" class="btn-overlay live-btn"><i class="fas fa-external-link-alt"></i> Live Demo</a>`;

    // GitHub Button HTML
    const githubBtnHTML = item.githubUrl 
      ? `<a href="${item.githubUrl}" target="_blank" rel="noopener noreferrer" class="btn-overlay github-btn"><i class="fab fa-github"></i> GitHub</a>` 
      : '';

    // Standard Card HTML matching original structure exactly
    return `
      <div class="showcase-card carousel-card">
        <div class="project-img-wrapper">
          <img src="${item.image}" alt="${item.title}" class="project-img" onerror="this.src='https://via.placeholder.com/600x350/1e293b/38bdf8?text=${item.placeholderText || 'Project'}'">
          <div class="project-overlay">
            <div class="overlay-content">
              <h3>${item.title}</h3>
              <p>${item.description}</p>
              <div class="tech-tags">
                ${tagsHTML}
              </div>
              <div class="overlay-buttons">
                ${demoBtnHTML}
                ${githubBtnHTML}
              </div>
            </div>
          </div>
        </div>
        <div class="card-footer-info">
          <h4>${item.footerTitle}</h4>
          <span class="project-type">${item.type}</span>
        </div>
      </div>
    `;
  }).join('');

  container.innerHTML = html;
}

// Render all sections on DOM Load
document.addEventListener("DOMContentLoaded", () => {
  renderCategoryProjects('ml-carousel', projectsData.ml);
  renderCategoryProjects('dl-carousel', projectsData.dl);
  renderCategoryProjects('genai-carousel', projectsData.genai);
  renderCategoryProjects('wed-carousel', projectsData.wed);
});